  <div class="card o"><h3>以为换个更好的工具就好<span class="sev md">小心</span></h3><p>原因：作者已经在用带 AI 的 wiki，它仍不知道“删除步骤”对眼前的工作有没有用。</p><div class="do">解法：先补问题，再考虑工具；没有问题时，换工具只是换个地方存笔记。</div></div>
